import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:firebase_auth/firebase_auth.dart';

import '../models/message_model.dart';

class ChatService {
  final FirebaseFirestore _firestore = FirebaseFirestore.instance;
  final FirebaseAuth _firebaseAuth = FirebaseAuth.instance;

  String _getChatRoomId(String userId, String otherUserId) {
    final ids = [userId, otherUserId]..sort();
    return ids.join('_');
  }

  String _getDisplayName(Map<String, dynamic> data) {
    final firstName =
        (data['fName'] ?? data['firstName'] ?? '').toString().trim();
    final lastName =
        (data['lName'] ?? data['lastName'] ?? '').toString().trim();

    final fullName = '$firstName $lastName'.trim();

    if (fullName.isNotEmpty) return fullName;

    final username = (data['username'] ?? '').toString().trim();

    if (username.isNotEmpty) return username;

    return 'Unknown user';
  }

  // Get a profile using the Firebase Auth UID.
  Future<Map<String, dynamic>> _getUserProfile(String uid) async {
    final users = _firestore.collection('users');

    // Normal profiles are saved at users/{Firebase Auth UID}.
    final directDoc = await users.doc(uid).get();

    if (directDoc.exists) {
      final data = directDoc.data() ?? {};

      return {
        ...data,
        'uid': directDoc.id,
        'firstName': data['fName'] ?? data['firstName'] ?? '',
        'lastName': data['lName'] ?? data['lastName'] ?? '',
        'email': data['emailAddress'] ?? data['email'] ?? '',
        'username': data['username'] ?? '',
      };
    }

    // Fallback for older profiles with autogenerated document IDs.
    final query = await users.where('uid', isEqualTo: uid).limit(1).get();

    if (query.docs.isNotEmpty) {
      final doc = query.docs.first;
      final data = doc.data();

      return {
        ...data,
        'uid': (data['uid'] ?? doc.id).toString(),
        'firstName': data['fName'] ?? data['firstName'] ?? '',
        'lastName': data['lName'] ?? data['lastName'] ?? '',
        'email': data['emailAddress'] ?? data['email'] ?? '',
        'username': data['username'] ?? '',
      };
    }

    throw StateError('No user profile found for UID: $uid');
  }

  // List registered users, excluding the signed-in user.
  Stream<List<Map<String, dynamic>>> getUsersStream() {
    final currentUser = _firebaseAuth.currentUser;

    if (currentUser == null) {
      return Stream.value([]);
    }

    return _firestore.collection('users').snapshots().map((snapshot) {
      final users = snapshot.docs
          .where((doc) => doc.id != currentUser.uid)
          .map((doc) {
        final data = doc.data();

        return <String, dynamic>{
          ...data,
          // The Firestore document ID is the actual UID.
          'uid': doc.id,
          'firstName': data['fName'] ?? data['firstName'] ?? '',
          'lastName': data['lName'] ?? data['lastName'] ?? '',
          'email': data['emailAddress'] ?? data['email'] ?? '',
          'username': data['username'] ?? '',
        };
      }).toList();

      users.sort(
        (a, b) => _getDisplayName(a)
            .toLowerCase()
            .compareTo(_getDisplayName(b).toLowerCase()),
      );

      return users;
    });
  }

  // Get the conversations belonging to the signed-in user.
  Stream<List<Map<String, dynamic>>> getConversationsStream() {
    final currentUser = _firebaseAuth.currentUser;

    if (currentUser == null) {
      return Stream.value([]);
    }

    return _firestore
        .collection('chat_rooms')
        .where('participants', arrayContains: currentUser.uid)
        .snapshots()
        .asyncMap((snapshot) async {
      final conversations = <Map<String, dynamic>>[];

      for (final doc in snapshot.docs) {
        final data = doc.data();

        final participants = List<String>.from(
          (data['participants'] ?? []).map((id) => id.toString()),
        );

        final otherUsers = participants
            .where((uid) => uid != currentUser.uid)
            .toList();

        if (otherUsers.isEmpty) continue;

        final otherUserId = otherUsers.first;

        final names = Map<String, dynamic>.from(
          data['participantNames'] ?? {},
        );

        final savedName = (names[otherUserId] ?? '').toString().trim();
        var otherName = savedName;

        // Prefer the latest name from the actual recipient's profile.
        try {
          final profile = await _getUserProfile(otherUserId);
          final profileName = _getDisplayName(profile);

          if (profileName != 'Unknown user') {
            otherName = profileName;
          }
        } catch (error) {
          print('CHAT PROFILE ERROR: $error');
        }

        if (otherName.isEmpty) {
          otherName = 'Unknown user';
        }

        conversations.add({
          'roomId': doc.id,
          'otherUserId': otherUserId,
          'otherName': otherName,
          'lastMessage': (data['lastMessage'] ?? '').toString(),
          'lastSenderId': (data['lastSenderId'] ?? '').toString(),
          'lastMessageAt': data['lastMessageAt'] is Timestamp
              ? data['lastMessageAt'] as Timestamp
              : Timestamp(0, 0),
        });
      }

      conversations.sort((a, b) {
        final aTime = a['lastMessageAt'] as Timestamp;
        final bTime = b['lastMessageAt'] as Timestamp;
        return bTime.compareTo(aTime);
      });

      return conversations;
    });
  }

  // Send a message to the selected recipient.
  Future<void> sendMessage(String receiverId, String message) async {
    final currentUser = _firebaseAuth.currentUser;

    if (currentUser == null) {
      throw StateError('Please sign in before sending a message.');
    }

    final text = message.trim();

    if (text.isEmpty) return;

    if (receiverId.isEmpty || receiverId == currentUser.uid) {
      throw ArgumentError('Invalid chat recipient.');
    }

    if (text.length > 5000) {
      throw ArgumentError('Message cannot exceed 5000 characters.');
    }

    final roomId = _getChatRoomId(currentUser.uid, receiverId);
    final roomRef = _firestore.collection('chat_rooms').doc(roomId);

    try {
      final currentProfile = await _getUserProfile(currentUser.uid);
      final receiverProfile = await _getUserProfile(receiverId);

      final currentName = _getDisplayName(currentProfile);
      final receiverName = _getDisplayName(receiverProfile);

      final roomSnapshot = await roomRef.get();
      final now = Timestamp.now();

      if (!roomSnapshot.exists) {
        await roomRef.set({
          'participants': [currentUser.uid, receiverId],
          'participantNames': {
            currentUser.uid: currentName,
            receiverId: receiverName,
          },
          'lastMessage': text,
          'lastMessageAt': now,
          'lastSenderId': currentUser.uid,
        });
      } else {
        final roomData = roomSnapshot.data() ?? {};

        final participants = List<String>.from(
          (roomData['participants'] ?? []).map((id) => id.toString()),
        );

        if (!participants.contains(currentUser.uid) ||
            !participants.contains(receiverId)) {
          throw StateError(
            'The existing chat room has incorrect participants. '
            'Check its participants field in Firestore.',
          );
        }
      }

      final newMessage = MessageModel(
        senderId: currentUser.uid,
        senderEmail: currentUser.email ?? '',
        receiverId: receiverId,
        message: text,
        timestamp: now,
        status: 'sent',
        deliveredAt: null,
        readAt: null,
      );

      await roomRef.collection('messages').add(newMessage.toMap());

      await roomRef.update({
        'lastMessage': text,
        'lastMessageAt': now,
        'lastSenderId': currentUser.uid,
      });
    } catch (error) {
      print('CHAT SEND ERROR: $error');
      rethrow;
    }
  }

  // Get messages between two different users.
  Stream<QuerySnapshot<Map<String, dynamic>>> getMessages(
    String userId,
    String otherUserId,
  ) {
    if (userId == otherUserId) {
      throw ArgumentError('A chat requires two different users.');
    }

    final roomId = _getChatRoomId(userId, otherUserId);

    return _firestore
        .collection('chat_rooms')
        .doc(roomId)
        .collection('messages')
        .orderBy('timestamp', descending: true)
        .snapshots();
  }

  // Mark received messages as delivered.
  Future<void> markMessagesDelivered(String otherUserId) async {
    final currentUser = _firebaseAuth.currentUser;

    if (currentUser == null ||
        otherUserId.isEmpty ||
        otherUserId == currentUser.uid) {
      return;
    }

    final roomId = _getChatRoomId(currentUser.uid, otherUserId);

    final messagesRef = _firestore
        .collection('chat_rooms')
        .doc(roomId)
        .collection('messages');

    final snapshot = await messagesRef
        .where('receiverId', isEqualTo: currentUser.uid)
        .get();

    final pendingMessages = snapshot.docs
        .where((doc) => doc.data()['status'] == 'sent')
        .toList();

    for (var i = 0; i < pendingMessages.length; i += 450) {
      final end = (i + 450 < pendingMessages.length)
          ? i + 450
          : pendingMessages.length;

      final batch = _firestore.batch();

      for (final doc in pendingMessages.sublist(i, end)) {
        batch.update(doc.reference, {
          'status': 'delivered',
          'deliveredAt': FieldValue.serverTimestamp(),
        });
      }

      await batch.commit();
    }
  }

  // Mark received messages as read.
  Future<void> markMessagesRead(String otherUserId) async {
    final currentUser = _firebaseAuth.currentUser;

    if (currentUser == null ||
        otherUserId.isEmpty ||
        otherUserId == currentUser.uid) {
      return;
    }

    final roomId = _getChatRoomId(currentUser.uid, otherUserId);

    final messagesRef = _firestore
        .collection('chat_rooms')
        .doc(roomId)
        .collection('messages');

    final snapshot = await messagesRef
        .where('receiverId', isEqualTo: currentUser.uid)
        .get();

    final unreadMessages = snapshot.docs.where((doc) {
      final status = (doc.data()['status'] ?? 'sent').toString();
      return status == 'sent' || status == 'delivered';
    }).toList();

    for (var i = 0; i < unreadMessages.length; i += 450) {
      final end = (i + 450 < unreadMessages.length)
          ? i + 450
          : unreadMessages.length;

      final batch = _firestore.batch();

      for (final doc in unreadMessages.sublist(i, end)) {
        final data = doc.data();

        batch.update(doc.reference, {
          'status': 'read',
          'deliveredAt':
              data['deliveredAt'] ?? FieldValue.serverTimestamp(),
          'readAt': FieldValue.serverTimestamp(),
        });
      }

      await batch.commit();
    }
  }
}